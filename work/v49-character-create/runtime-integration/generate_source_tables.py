"""Generate C99 tables only from previously finalized v49 source artifacts."""
from pathlib import Path
import json,zlib,hashlib
ROOT=Path(r'C:\Users\rwill\Documents\Opem Amalur')
BASE=ROOT/'work/v49-character-create'
OUT=BASE/'runtime-integration'
cd=json.loads((BASE/'analysis/character-data-tables.json').read_text())
catalog=json.loads((BASE/'staged-source/creation-source-catalogue.json').read_text())
pal=json.loads((BASE/'analysis/resolved-cosmetic-palettes.json').read_text())['types']
assets=json.loads((BASE/'analysis/source-customization-options.json').read_text())['records']
races=['Almain','Varani','Ljosalfar','Dokkalfar'];sexes=['Male','Female']
assetkeys=['Head','Hair','Beard','Ears','Tattoo','FaceAccesory']
colorkeys=['SkinTone','HairColor','EyeColor','TattooColor','BeardColor','Eyebrow','EyeLiner','Lipstick']
alphakeys=['TattooAlpha','EyebrowAlpha','EyeLinerAlpha','LipstickAlpha']
skillkeys=['Alchemy','Blacksmithing','DetectHidden','Dispelling','Lockpicking','Mercantile','Persuasion','Sagecraft','Stealth']
racebits={'Almain':64,'Varani':128,'Ljosalfar':512,'Dokkalfar':1024}
def appearance(d):
 return [[d.get(k,0) for k in assetkeys],[d.get(k,0) for k in colorkeys],[d.get(k,0) for k in alphakeys]]
def init(d):return '{'+','.join('{'+','.join(str(v)+'u' for v in a)+'}' for a in appearance(d))+'}'
canonical={'types':[],'assets':[]}
types=[]
for race in races:
 for sex in sexes:
  typ=race+'_'+sex
  row=next(x for x in catalog['types'] if x['type']==typ)
  colors=[[v['words'] for v in pal[typ][k]['records']] for k in colorkeys]
  canonical['types'].append({'name':typ,'default':appearance(cd['m_default_customization'][typ]),'presets':[appearance(cd['m_customization_presets'][typ][str(i)]) for i in range(1,6)],'colors':colors,'race_hash':row['race_hash'],'sex_hash':row['gender_hash'],'player':row['full_player_simtype'],'lite':row['creator_simtype'],'rig':row['rig_fab'],'name_default':row['default_name'],'patrons':row['allowed_patrons'],'skills':row['source_skill_bonus_raw']})
  types.append(row)
for a in assets:canonical['assets'].append([a[k] for k in ['asset_id','category_hash','race_mask','gender_mask']])
canonical_bytes=json.dumps(canonical,sort_keys=True,separators=(',',':')).encode()
crc=zlib.crc32(canonical_bytes)&0xffffffff
h="""#ifndef OA_CREATION_SOURCE_TABLES_H
#define OA_CREATION_SOURCE_TABLES_H
#include "oa_creation.h"
typedef struct oa_creation_color_view {const oa_creation_color_record *records;size_t count;} oa_creation_color_view;
typedef struct oa_creation_asset_row {uint32_t id,category,race_mask,sex_mask;} oa_creation_asset_row;
extern const oa_creation_source_type oa_creation_types_data[8];
extern const oa_creation_appearance oa_creation_presets_data[8][5];
extern const oa_creation_patron oa_creation_patrons_data[4][6];
extern const int16_t oa_creation_skills_data[4][9];
extern const oa_creation_color_view oa_creation_colors_data[8][8];
extern const oa_creation_asset_row oa_creation_assets_data[];
extern const size_t oa_creation_assets_count;
extern const uint32_t oa_creation_category_hashes[6];
#define OA_CREATION_SOURCE_CRC """+hex(crc)+"""u
#endif
"""
lines=['/* Generated by generate_source_tables.py; source IDs/indices/words retained. */','#include "oa_creation_source_tables.h"','const char *const oa_creation_skill_names[9]={'+','.join(json.dumps(x) for x in skillkeys)+'};','const uint32_t oa_creation_category_hashes[6]={701554u,481813u,1139995u,771605u,1756520u,9441502u};','const oa_creation_source_type oa_creation_types_data[8]={']
for row in types:
 race,sex=row['race'],row['gender'];typ=row['type']
 fields=','.join(json.dumps(x) for x in [race,sex,row['default_name']])+','+','.join(str(row[k])+'u' for k in ['race_hash','gender_hash','full_player_simtype','creator_simtype','rig_fab'])+','+str(racebits[race])+'u,'+str(1 if sex=='Male' else 2)+'u,'+init(cd['m_default_customization'][typ])
 lines+=['{'+fields+'},']
lines+=['};','const oa_creation_appearance oa_creation_presets_data[8][5]={']
for row in types:lines+=['{'+','.join(init(cd['m_customization_presets'][row['type']][str(i)]) for i in range(1,6))+'},']
lines+=['};','const oa_creation_patron oa_creation_patrons_data[4][6]={']
for race in races:
 names=[cd['m_patrons_by_race'][race][str(i)] for i in range(1,7)]
 lines+=['{'+','.join('{'+json.dumps(n)+','+str(cd['m_patron_buffs'][n])+'u}' for n in names)+'},']
lines+=['};','const int16_t oa_creation_skills_data[4][9]={']
for race in races:lines+=['{'+','.join(str(cd['m_skills_by_race'][race][x]) for x in skillkeys)+'},']
lines+=['};']
views=[]
for ti,row in enumerate(types):
 vr=[]
 for ci,key in enumerate(colorkeys):
  records=pal[row['type']][key]['records']
  if records:
   name=f'colors_{ti}_{ci}'
   lines+=['static const oa_creation_color_record '+name+'[]={']
   lines+=['{{'+','.join(str(x)+'u' for x in rec['words'])+'}},' for rec in records]
   lines+=['};'];vr.append('{'+name+','+str(len(records))+'u}')
  else:vr.append('{0,0}')
 views.append('{'+','.join(vr)+'}')
lines+=['const oa_creation_color_view oa_creation_colors_data[8][8]={',',\n'.join(views),'};','const oa_creation_asset_row oa_creation_assets_data[]={']
for a in assets:lines+=['{'+','.join(str(a[k])+'u' for k in ['asset_id','category_hash','race_mask','gender_mask'])+'},']
lines+=['};','const size_t oa_creation_assets_count=sizeof(oa_creation_assets_data)/sizeof(oa_creation_assets_data[0]);']
(OUT/'oa_creation_source_tables.h').write_text(h,encoding='utf-8')
(OUT/'oa_creation_source_tables.c').write_text('\n'.join(lines)+'\n',encoding='utf-8')
(OUT/'source-tables-receipt.json').write_text(json.dumps({'catalogue_crc32':hex(crc),'canonical_source_sha256':hashlib.sha256(canonical_bytes).hexdigest(),'types':len(types),'presets':40,'asset_rows':len(assets),'palette_records':sum(len(v) for t in canonical['types'] for v in t['colors']),'policy':'Exact source records; no unknown preset fallback, tint conversion, availability predicate or animation compatibility invented.','inputs':{str(p.relative_to(BASE)):hashlib.sha256(p.read_bytes()).hexdigest() for p in [BASE/'analysis/character-data-tables.json',BASE/'staged-source/creation-source-catalogue.json',BASE/'analysis/resolved-cosmetic-palettes.json',BASE/'analysis/source-customization-options.json']}},indent=2))
print('generated',len(lines),'lines','crc',hex(crc))
