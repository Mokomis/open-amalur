"""Choose where a zone's test start is: the placed character nearest the middle of the zone's characters. Writes town_start.inc beside the zone's town_live.inc. This place is a test choice, not a recovered spawn."""
import json,os,struct,sys
from pathlib import Path
import numpy as np
zone=Path(sys.argv[1]);actors=Path(sys.argv[2]);area,name=sys.argv[3],sys.argv[4]
b=(actors/"index.bin").read_bytes();Ty,N=struct.unpack_from("<II",b,4);o=12+Ty*76
A=np.array([struct.unpack_from("<4f",b,o+i*20)[:3] for i in range(N)])
m=np.median(A,axis=0);a=A[np.argmin(((A[:,:2]-m[:2])**2).sum(1))]
print("characters",N,"median",m.round(),"start",a.round(1))
(zone/"town_start.inc").write_text("/* Test start of this zone, generated by zone_start.py. */\n#define OA_LIVE_START_X %.1ff\n#define OA_LIVE_START_Y %.1ff\n#define OA_LIVE_START_Z %.1ff\n#define OA_LIVE_AREA \"%s\"\n#define OA_LIVE_ZONE \"%s\"\n#define OA_LIVE_HAS_SHOP 0\n"%(a[0],a[1],a[2],area,name))
(zone/"zone_start.txt").write_text("%.1f %.1f"%(a[0],a[1]))
